    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String texto = jTextField1.getText().trim();
        if (texto.isEmpty()) {
            cargarTabla();
            return;
        }
        Estacion est = controlador.buscarEstacion(texto);
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tablaEstaciones.getModel();
        modelo.setRowCount(0);
        if (est != null) {
            Object[] fila = {est.getId(), est.getNombre(), est.getLinea(), est.getZona(), est.getCapacidadPasajerosHora()};
            modelo.addRow(fila);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Estacion no encontrada.");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

