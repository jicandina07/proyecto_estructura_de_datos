    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int fila = tablaEstaciones.getSelectedRow();
        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione una estacion de la tabla.");
            return;
        }
        String id = tablaEstaciones.getValueAt(fila, 0).toString();
        int resp = javax.swing.JOptionPane.showConfirmDialog(this, "¿Eliminar la estacion " + id + " y sus conexiones?", "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);
        if (resp == javax.swing.JOptionPane.YES_OPTION) {
            controlador.eliminarEstacion(id);
            cargarTabla();
            if (principal != null) principal.actualizarMapa();
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

