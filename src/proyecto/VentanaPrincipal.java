    private void cargarRedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cargarRedActionPerformed
        // TODO add your handling code here:
        javax.swing.JFileChooser chooser = new javax.swing.JFileChooser();
        chooser.setDialogTitle("Seleccione el archivo CSV de ESTACIONES");
        if (chooser.showOpenDialog(this) == javax.swing.JFileChooser.APPROVE_OPTION) {
            java.io.File archEstaciones = chooser.getSelectedFile();
            chooser.setDialogTitle("Seleccione el archivo CSV de CONEXIONES");
            if (chooser.showOpenDialog(this) == javax.swing.JFileChooser.APPROVE_OPTION) {
                java.io.File archConexiones = chooser.getSelectedFile();
                boolean cargado = controlador.cargarArchivos(archEstaciones, archConexiones);
                if (cargado) {
                    lblArchivo.setText("Archivo: " + archEstaciones.getName());
                    actualizarMapa();
                    javax.swing.JOptionPane.showMessageDialog(this, "Red cargada correctamente.");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Error al leer los archivos CSV.");
                }
            }
        }
    }//GEN-LAST:event_cargarRedActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        javax.swing.JFileChooser chooser = new javax.swing.JFileChooser();
        chooser.setDialogTitle("Guardar CSV de ESTACIONES");
        if (chooser.showSaveDialog(this) == javax.swing.JFileChooser.APPROVE_OPTION) {
            String rutaEst = chooser.getSelectedFile().getAbsolutePath();
            if (!rutaEst.endsWith(".csv")) rutaEst = rutaEst + ".csv";
            chooser.setDialogTitle("Guardar CSV de CONEXIONES");
            if (chooser.showSaveDialog(this) == javax.swing.JFileChooser.APPROVE_OPTION) {
                String rutaCon = chooser.getSelectedFile().getAbsolutePath();
                if (!rutaCon.endsWith(".csv")) rutaCon = rutaCon + ".csv";
                if (controlador.guardarArchivos(rutaEst, rutaCon)) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Archivos guardados con exito.");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar los archivos.");
                }
            }
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnSalirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalirActionPerformed
        // TODO add your handling code here:
        if (controlador.hayCambiosSinGuardar()) {
            int resp = javax.swing.JOptionPane.showConfirmDialog(this, "Hay cambios sin guardar. ¿Desea salir igual?", "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);
            if (resp != javax.swing.JOptionPane.YES_OPTION) {
                return;
            }
        }
        System.exit(0);
    }//GEN-LAST:event_btnSalirActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String texto = areaBuscar.getText().trim();
        if (texto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Escriba el ID o nombre de la estacion.");
            return;
        }
        Estacion est = controlador.buscarEstacion(texto);
        if (est == null) {
            areaEstacion.setText("No se encontro ninguna estacion con: " + texto);
        } else {
            String info = "ID: " + est.getId() + "\n"
                        + "Nombre: " + est.getNombre() + "\n"
                        + "Linea: " + est.getLinea() + "\n"
                        + "Zona: " + est.getZona() + "\n"
                        + "Capacidad: " + est.getCapacidadPasajerosHora() + " pas/h\n"
                        + "Conexiones: " + est.getTamañoConexiones();
            areaEstacion.setText(info);
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

